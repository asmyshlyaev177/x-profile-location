// Lowercased alias (and canonical name) → canonical name. Canonical names are
// seeded first so aliases win the tie: 'Czech Republic' is a COUNTRY_FLAGS key
// in its own right, and it must still resolve to 'Czechia'.
const CANONICAL_BY_NAME = new Map<string, string>()
for (const name of [
  ...Object.keys(COUNTRY_FLAGS),
  ...Object.keys(REGION_FLAGS),
]) {
  CANONICAL_BY_NAME.set(name.toLowerCase(), name)
}
for (const [canonical, aliases] of Object.entries(LOCATION_ALIASES)) {
  for (const alias of aliases) {
    CANONICAL_BY_NAME.set(alias.toLowerCase(), canonical)
  }
}

/**
 * The one name a location is stored and compared under. Unknown locations come
 * back trimmed but otherwise untouched — X's vocabulary is not ours to police,
 * and a name we don't know yet must still be blockable.
 */
export function canonicalLocation(value: string): string {
  const trimmed = value.trim()
  return CANONICAL_BY_NAME.get(trimmed.toLowerCase()) ?? trimmed
}

